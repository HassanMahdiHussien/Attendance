beforeEach(function (): void {
    $company = Company::factory()->create();
    app(TenantContext::class)->setCompany($company);
    $actor = User::factory()->create(['company_id' => $company->id, 'primary_role' => UserRole::HrStaff]);
    actingInAdminTenant($this, $actor, $company);
});

afterEach(function (): void {
    Filament::setTenant(null);
    app(TenantContext::class)->clear();
});

test('empty HR lists keep their column headings and a clear empty message', function (string $page, string $heading, string $empty): void {
    Livewire::test($page)->assertSee($heading)->assertSee($empty);
})->with([
    'daily' => [DailyAttendance::class, 'Employee', 'No assessed days match these filters.'],
    'review' => [ReviewQueue::class, 'Employee', 'No days match this review filter.'],
    'issues' => [AttendanceIssues::class, 'Issues by type', 'No issues for this state.'],
    'punches' => [AttendancePunches::class, 'Punch viewer', 'No records match this view.'],
    'devices' => [AttendanceDevices::class, 'Serial', 'No records match this view.'],
    'cases' => [FollowUpCasesPage::class, 'Issue', 'No records'],
    'attendance batches' => [AttendanceBatches::class, 'Final counts', 'No records match this view.'],
    'exports' => [AttendanceExportsPage::class, 'Generated by', 'No records match this view.'],
    'leave requests' => [LeaveRequests::class, 'Form number', 'No records match this view.'],
    'leave batches' => [LeaveBatches::class, 'Uploaded at', 'No records match this view.'],
    'balance batches' => [LeaveBalanceBatches::class, 'Balance date', 'No records match this view.'],
]);

